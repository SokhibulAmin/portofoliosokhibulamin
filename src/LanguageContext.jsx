const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    const savedLanguage = window.localStorage.getItem("portfolio-language");
    return savedLanguage === "en" || savedLanguage === "zh" ? savedLanguage : "id";
  });

  useEffect(() => {
    document.documentElement.lang = language === "zh" ? "zh-CN" : language;
    window.localStorage.setItem("portfolio-language", language);
    document.title = `Sokhibul Amin — ${language === "id" ? "Portofolio Personal" : language === "en" ? "Personal Portfolio" : "个人作品集"}`;
    document.querySelector('meta[name="description"]')?.setAttribute("content", translations[language].metaDescription);
    document.querySelector('meta[property="og:description"]')?.setAttribute("content", translations[language].metaDescription);
  }, [language]);

  const value = useMemo(() => ({
    language,
    setLanguage,
    t: (key, values) => {
      const translation = translations[language][key] ?? translations.id[key] ?? key;
      return typeof translation === "function" ? translation(values) : translation;
    },
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage must be used within a LanguageProvider");
  }
  return context;
}

